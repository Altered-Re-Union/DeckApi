using DeckApi.Data;
using DeckApi.Import;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.DependencyInjection;
using Npgsql;

namespace DeckApi.Tests.Integration;

[Collection(IntegrationCollection.Name)]
public sealed class LegacyImportTests(DeckApiFactory factory)
{
    /// <summary>Old decks-api schema, as produced by its Doctrine migrations (Version20260422162231 → Version20260922000000).</summary>
    private const string LegacySchema = """
        CREATE TABLE "user" (id UUID NOT NULL PRIMARY KEY, keycloak_id VARCHAR(255) NOT NULL UNIQUE, email VARCHAR(255), username VARCHAR(100),
            created_at TIMESTAMP(0) NOT NULL, updated_at TIMESTAMP(0), is_admin BOOLEAN DEFAULT false NOT NULL, locale VARCHAR(10));
        CREATE TABLE deck (id UUID NOT NULL PRIMARY KEY, name VARCHAR(150) NOT NULL, description TEXT, format VARCHAR(255), is_public BOOLEAN NOT NULL,
            created_at TIMESTAMP(0) NOT NULL, updated_at TIMESTAMP(0), stats JSON, user_id UUID NOT NULL REFERENCES "user"(id), is_draft BOOLEAN NOT NULL,
            format_errors JSON, legal BOOLEAN NOT NULL, legality_detail JSON, altered_id VARCHAR(255) UNIQUE,
            view_count INT DEFAULT 0 NOT NULL, upvote_count INT DEFAULT 0 NOT NULL);
        CREATE TABLE deck_card (id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, card_reference VARCHAR(100) NOT NULL, quantity SMALLINT NOT NULL,
            deck_id UUID NOT NULL REFERENCES deck(id) ON DELETE CASCADE, name VARCHAR(255), UNIQUE (deck_id, card_reference));
        CREATE TABLE deck_upvote (id UUID NOT NULL PRIMARY KEY, deck_id UUID NOT NULL REFERENCES deck(id) ON DELETE CASCADE,
            user_id UUID NOT NULL REFERENCES "user"(id) ON DELETE CASCADE, created_at TIMESTAMP(0) NOT NULL, UNIQUE (deck_id, user_id));
        """;

    [Fact]
    public async Task Imports_users_decks_and_upvotes_idempotently()
    {
        var legacyConnection = await CreateLegacyDatabaseAsync();
        Guid owner = Guid.NewGuid(), voter = Guid.NewGuid(), deckId = Guid.NewGuid(), draftId = Guid.NewGuid();

        await using (var conn = new NpgsqlConnection(legacyConnection))
        {
            await conn.OpenAsync();
            await Exec(conn, "INSERT INTO \"user\" (id, keycloak_id, email, username, created_at, is_admin) VALUES (@o, 'kc-import-owner', 'o@x', 'Owner', now(), true), (@v, 'kc-import-voter', null, 'Voter', now(), false)",
                ("o", owner), ("v", voter));
            await Exec(conn, "INSERT INTO deck (id, name, format, is_public, created_at, updated_at, user_id, is_draft, legal, altered_id, view_count, upvote_count) " +
                "VALUES (@d, 'Imported', 'NO_UNIQUE', true, '2026-01-02 10:00:00', '2026-02-03 11:00:00', @o, false, false, 'altered-import-1', 12, 1), " +
                "(@dr, 'Draft', null, false, '2026-01-02 10:00:00', null, @o, true, false, null, 0, 0)",
                ("d", deckId), ("dr", draftId), ("o", owner));
            foreach (var line in TestCards.StandardAxDeck())
                await Exec(conn, "INSERT INTO deck_card (card_reference, quantity, deck_id) VALUES (@r, @q, @d)", ("r", line.Reference), ("q", (short)line.Quantity), ("d", deckId));
            await Exec(conn, "INSERT INTO deck_upvote (id, deck_id, user_id, created_at) VALUES (@id, @d, @v, now())", ("id", Guid.NewGuid()), ("d", deckId), ("v", voter));
        }

        var first = await RunImportAsync(legacyConnection);
        Assert.Equal((2, 2, 0, 1), (first.Users, first.DecksCreated, first.DecksUpdated, first.Upvotes));

        using (var scope = factory.Services.CreateScope())
        {
            var db = scope.ServiceProvider.GetRequiredService<DeckDbContext>();
            var deck = await db.Decks.Include(d => d.User).SingleAsync(d => d.Id == deckId);
            Assert.Equal(deckId, deck.LegacyId);
            Assert.Equal("nuc", deck.Format); // alias normalised
            Assert.True(deck.Legal);          // recomputed with the new rules
            Assert.Equal(39, deck.CardCount);
            Assert.Equal(12, deck.ViewCount);
            Assert.Equal("Owner", deck.User.Username);
            Assert.True(deck.User.IsAdmin);
            Assert.Equal(new DateTimeOffset(2026, 2, 3, 11, 0, 0, TimeSpan.Zero), deck.UpdatedAt);
            Assert.Equal(1, await db.DeckUpvotes.CountAsync(u => u.DeckId == deckId));
        }

        // Re-running is a no-op.
        var second = await RunImportAsync(legacyConnection);
        Assert.Equal((0, 0, 2, 0), (second.DecksCreated, second.DecksUpdated, second.DecksUnchanged, second.Upvotes));
    }

    private async Task<LegacyImporter.Report> RunImportAsync(string source)
    {
        using var scope = factory.Services.CreateScope();
        return await scope.ServiceProvider.GetRequiredService<LegacyImporter>().RunAsync(source, dryRun: false, CancellationToken.None);
    }

    private async Task<string> CreateLegacyDatabaseAsync()
    {
        var name = "legacy_" + Guid.NewGuid().ToString("N")[..8];
        await using (var admin = new NpgsqlConnection(factory.Postgres.GetConnectionString()))
        {
            await admin.OpenAsync();
            await Exec(admin, $"CREATE DATABASE {name}");
        }
        var connection = new NpgsqlConnectionStringBuilder(factory.Postgres.GetConnectionString()) { Database = name }.ConnectionString;
        await using var conn = new NpgsqlConnection(connection);
        await conn.OpenAsync();
        await Exec(conn, LegacySchema);
        return connection;
    }

    private static async Task Exec(NpgsqlConnection conn, string sql, params (string Name, object Value)[] parameters)
    {
        await using var cmd = new NpgsqlCommand(sql, conn);
        foreach (var (n, v) in parameters) cmd.Parameters.AddWithValue(n, v);
        await cmd.ExecuteNonQueryAsync();
    }
}
